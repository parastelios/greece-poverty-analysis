FIGDIR = ROOT / "docs" / "figures"


def figure(name, caption):
    path = FIGDIR / name
    if not path.exists():
        raise SystemExit(f"figure missing: {name}")
    svg = re.sub(r"^<\?xml[^>]*\?>\s*", "", path.read_text())
    svg = re.sub(r'\swidth="\d+"\s+height="\d+"', ' class="fig-svg"', svg, count=1)
    return (f'<figure class="fig">{svg}'
            f'<figcaption>{caption}</figcaption></figure>')

