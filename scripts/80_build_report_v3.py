def claim_box(cid, extra=""):
    """A claim container: canonical wording plus every mandatory caveat.

    The caveats are emitted FROM THE REGISTER, so a claim cannot appear in this
    document without them.
    """
    c = claims.loc[cid]
    cav = ""
    if isinstance(c.caveats, str) and c.caveats:
        items = "".join(f"<li>{x}</li>" for x in c.caveats.split(" | "))
        cav = f'<div class="caveats"><span class="cav-label">This claim carries:</span><ul>{items}</ul></div>'
    tier = f'<span class="tier">{c.tier}</span>'
    return (f'<div class="claim" data-claim-id="{cid}">'
            f'<div class="claim-head"><span class="cid">{cid}</span>{tier}</div>'
            f'<p class="claim-text">{c.canonical_wording}</p>{extra}{cav}</div>')


def ctx_box(cid, prose):
    """A context container carrying status, permitted, limitation and citation.

    All four parts are emitted together from the register. The prose argument is
    NEW writing for this document -- old text is never wrapped.
    """
    e = ctx.loc[cid]
    cite = ""
    if str(e.source_status) != "not applicable":
        url = f' <a href="{e.source_url}">{e.source_url}</a>' if isinstance(e.source_url, str) and e.source_url else ""
        detail = f" {e.source_detail}" if isinstance(e.source_detail, str) and e.source_detail else ""
        cite = f'<p class="cite"><strong>Source.</strong> {e.source}{detail}{url}</p>'
    return (f'<div class="ctx" data-context-id="{cid}">'
            f'<div class="ctx-head"><span class="cid">{cid}</span>'
            f'<span class="status">{e.status}</span></div>'
            f'<h4>{e.topic}</h4>{prose}'
            f'<p class="permitted"><strong>What may be concluded.</strong> {e.permitted}</p>'
            f'<p class="limitation"><strong>Limitation.</strong> {e.forbidden}</p>{cite}</div>')


